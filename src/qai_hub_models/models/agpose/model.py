MODEL_ID = __name__.split(".")[-2]
MODEL_ASSET_VERSION = 2
CKPT_ASSET_VERSION = 1

# Pretrained checkpoint — NOCS REAL275 dataset (DINOv2 backbone).
# Downloaded from the AG-Pose Google Drive:
# https://github.com/Leeiieeo/AG-Pose (see Data Preparation section).
AG_POSE_CKPT = CachedWebModelAsset.from_asset_store(
    MODEL_ID, CKPT_ASSET_VERSION, "epoch_30.pt"
)

# Golden input/output NPZ for numerical regression tests.
# Generated by running AGPoseCollection.from_pretrained() on a single
# NOCS REAL275 sample and saving inputs + outputs via np.savez().
AG_POSE_SAMPLE_INPUTS = CachedWebModelAsset.from_asset_store(
    MODEL_ID, MODEL_ASSET_VERSION, "agpose_collection_outputs6.npz"
)

# NOCS 6 object categories (0-indexed)
NUM_CATEGORIES = len(CATEGORY_NAMES)

# Checkpoint keys belonging to AGPoseRotationHead.
# Derived from upstream PoseSizeEstimator — these keys are stripped from
# the backbone state dict and loaded (with prefix removed) into the head.
_HEAD_PREFIXES = (
    "estimator.pose_mlp1.",
    "estimator.pose_mlp2.",
    "estimator.rotation_estimator.",
    "estimator.translation_estimator.",
    "estimator.size_estimator.",
)

# Keys present in the upstream checkpoint but not in either component.
_CHECKPOINT_ONLY_PREFIXES = ("reconstructor.",)


class AGPoseBackbone(BaseModel):
    """
    Component A (float) of the AGPose WorkbenchModelCollection.

    Runs DINOv2 + PointNet2 + IAKD + GAFA + pts_mlp1 + pts_mlp2 only.
    pose_mlp1, pose_mlp2, rotation/translation/size estimators all live in AGPoseRotationHead (float).

    Outputs (tuple of 2):
        pre_pose_feat : (B, 384, 96) — pre-pose feature before pose_mlp1, fed to AGPoseRotationHead
        c             : (B, 3)       — point cloud centroid for translation reconstruction
    """

    def __init__(self, model: nn.Module) -> None:
        super().__init__()
        self.model = model

    @classmethod
    def from_pretrained(
        cls,
        ckpt_path: str | None = None,
        state_dict: dict | None = None,
    ) -> AGPoseBackbone:
        repo_path = EXTERNAL_REPO_PATHS["ag_pose"]
        with ag_pose_repo_paths():
            with open(repo_path / "config" / "REAL" / "camera_real.yaml") as f:
                cfg = to_ns(yaml.safe_load(f))

            net_backbone = NetBackbone(cfg.pose_net)
        net_backbone.eval()

        # Replace AttnBlock/SelfAttnBlock instances with ONNX-compatible
        # per-instance patched versions — avoids global class-level side effects.
        # Must be called before any forward pass through NetBackbone.
        patch_manual_multihead_attn(net_backbone)
        if cfg.pose_net.rgb_backbone == "dino":
            patch_dinov2_attention(net_backbone.rgb_extractor)

        if state_dict is None:
            ckpt = str(AG_POSE_CKPT.fetch()) if ckpt_path is None else ckpt_path
            state_dict = torch.load(ckpt, map_location="cpu", weights_only=True)

        # Strip all layers that moved to the float head
        # _HEAD_PREFIXES and _CHECKPOINT_ONLY_PREFIXES are defined at module level.
        backbone_state = {
            k: v
            for k, v in state_dict.items()
            if not any(
                k.startswith(p) for p in _HEAD_PREFIXES + _CHECKPOINT_ONLY_PREFIXES
            )
        }
        # strict=True works because:
        # - reconstructor.* filtered above
        # - nocs_predictor.bins_center is register_buffer(persistent=False)
        #   so it is excluded from state_dict() and not expected in checkpoint.
        # Pad pts_mlp1/2 first-conv weights from (32,3,1) -> (32,4,1) to match
        # the 4-channel Conv1d in PoseSizeEstimatorBackbone. The fourth channel
        # weight column is zero so runtime behaviour is identical.
        for key in (
            "estimator.pts_mlp1.0.weight",
            "estimator.pts_mlp2.0.weight",
        ):
            if key in backbone_state:
                w = backbone_state[key]  # (32, 3, 1)
                pad = torch.zeros(w.shape[0], 1, w.shape[2], dtype=w.dtype)
                backbone_state[key] = torch.cat([w, pad], dim=1)  # (32, 4, 1)

        net_backbone.load_state_dict(backbone_state, strict=True)

        # The checkpoint load restores the original patch-embed weights.
        # Reapply the fold so raw [0, 1] RGB inputs remain valid.
        if cfg.pose_net.rgb_backbone == "dino":
            fold_dinov2_imagenet_norm(net_backbone.rgb_extractor)

        return cls(net_backbone)

    def forward(
        self,
        category_label: torch.Tensor,
        choose: torch.Tensor,
        fps1: torch.Tensor,
        fps2: torch.Tensor,
        fps3: torch.Tensor,
        fps4: torch.Tensor,
        pts: torch.Tensor,
        rgb: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """
        Run backbone forward pass.

        Parameters
        ----------
        category_label
            Object category ID tensor of shape (B,).
        choose
            Index mapping from pts to flattened image pixels, shape (B, N).
        fps1
            Pre-computed FPS indices for SA layer 1, shape (B, 512).
        fps2
            Pre-computed FPS indices for SA layer 2, shape (B, 256).
        fps3
            Pre-computed FPS indices for SA layer 3, shape (B, 128).
        fps4
            Pre-computed FPS indices for SA layer 4, shape (B, 64).
        pts
            3D point cloud in camera coordinates, shape (B, N, 3).
        rgb
            RGB image tensor of shape (B, 3, H, W).

        Returns
        -------
        pre_pose_feat : torch.Tensor
            Pre-pose feature of shape (B, 384, 96).
        c : torch.Tensor
            Point cloud centroid of shape (B, 3).
        """
        inputs = {
            "rgb": rgb,
            "pts": pts,
            "choose": choose,
            "category_label": category_label,
        }
        pre_pose_feat, c = self.model(
            inputs,
            fps_indices=[fps1.int(), fps2.int(), fps3.int(), fps4.int()],
        )
        return (
            pre_pose_feat.float(),  # (B, 384, 96)
            c.float(),  # (B, 3)
        )

    def component_precision(self) -> Precision:
        return Precision.float

    def get_input_spec(
        self,
        batch_size: int = 1,
        num_points: int = NUM_POINTS,
        height: int = IMAGE_SIZE,
        width: int = IMAGE_SIZE,
    ) -> InputSpec:
        return {
            "category_label": TensorSpec(
                shape=(batch_size,),
                dtype="int32",
                io_type=IoType.TENSOR,
                description=(
                    "Object category ID: "
                    "0=bottle, 1=bowl, 2=camera, 3=can, 4=laptop, 5=mug"
                ),
            ),
            "choose": TensorSpec(
                shape=(batch_size, num_points),
                dtype="int32",
                io_type=IoType.TENSOR,
                description="Index mapping from pts to flattened image pixels",
            ),
            "fps1": TensorSpec(
                shape=(batch_size, 512),
                dtype="int32",
                io_type=IoType.TENSOR,
                description="Pre-computed FPS indices for SA layer 1",
            ),
            "fps2": TensorSpec(
                shape=(batch_size, 256),
                dtype="int32",
                io_type=IoType.TENSOR,
                description="Pre-computed FPS indices for SA layer 2",
            ),
            "fps3": TensorSpec(
                shape=(batch_size, 128),
                dtype="int32",
                io_type=IoType.TENSOR,
                description="Pre-computed FPS indices for SA layer 3",
            ),
            "fps4": TensorSpec(
                shape=(batch_size, 64),
                dtype="int32",
                io_type=IoType.TENSOR,
                description="Pre-computed FPS indices for SA layer 4",
            ),
            "pts": TensorSpec(
                shape=(batch_size, num_points, 3),
                dtype="float32",
                io_type=IoType.TENSOR,
                description="3D point cloud in camera coordinates (metres)",
            ),
            "rgb": TensorSpec(
                shape=(batch_size, 3, height, width),
                dtype="float32",
                io_type=IoType.IMAGE,
                value_range=(0.0, 1.0),
                apply_runtime_channel_reordering=True,
            ),
        }

    def get_output_spec(self, batch_size: int = 1) -> OutputSpec:
        return {
            "pre_pose_feat": TensorSpec(
                shape=(batch_size, 384, 96),
                dtype="float32",
                io_type=IoType.TENSOR,
                description="Pre-pooled pose feature (B,384,96) — input to float head",
            ),
            "c": TensorSpec(
                shape=(batch_size, 3),
                dtype="float32",
                io_type=IoType.TENSOR,
                description="Point cloud centroid for translation reconstruction",
            ),
        }

    def get_hub_compile_options(
        self,
        target_runtime: TargetRuntime,
        precision: Precision,
        other_compile_options: str = "",
        device: Device | None = None,
        context_graph_name: str | None = None,
    ) -> str:
        opts = super().get_hub_compile_options(
            target_runtime, precision, other_compile_options, device, context_graph_name
        )
        if target_runtime in (
            TargetRuntime.QNN_CONTEXT_BINARY,
            TargetRuntime.QNN_DLC,
            TargetRuntime.TFLITE,
        ):
            opts += " --truncate_64bit_io --truncate_64bit_tensors"

        return opts

    def _sample_inputs_impl(
        self,
        input_spec: InputSpec | None = None,
        *args: Any,
        **kwargs: Any,
    ) -> dict[str, list[np.ndarray]]:
        """Load sample inputs from the bundled golden asset.

        Uses the pre-computed golden NPZ rather than the private REAL275
        dataset so that export, demo, and validate work without dataset
        configuration. FPS indices are loaded from the golden asset directly
        to ensure they are consistent with the stored point cloud sample.
        """
        golden = np.load(str(AG_POSE_SAMPLE_INPUTS.fetch()))
        return {
            "category_label": [golden["category_label"]],
            "choose": [golden["choose"]],
            "fps1": [golden["fps1"]],
            "fps2": [golden["fps2"]],
            "fps3": [golden["fps3"]],
            "fps4": [golden["fps4"]],
            "pts": [golden["pts"]],
            "rgb": [golden["rgb"]],
        }


class AGPoseRotationHead(BaseModel):
    """
    Component B (float) of the AGPose WorkbenchModelCollection.

    Takes pre_pose_feat (B, 384, 96) and c (B, 3) from AGPoseBackbone.
    Runs pose_mlp1 → global concat → pose_mlp2 → all 3 estimators in float.

    Inputs:
        pre_pose_feat : (B, 384, 96)
        c             : (B, 3)

    Outputs:
        pred_rotation    : (B, 3, 3)
        pred_translation : (B, 3)
        pred_size        : (B, 3)
    """

    def __init__(self, model: nn.Module) -> None:
        super().__init__()
        self.model = model

    @classmethod
    def from_pretrained(
        cls,
        ckpt_path: str | None = None,
        state_dict: dict | None = None,
    ) -> AGPoseRotationHead:
        rotation_head = PoseSizeEstimatorRotationHead()
        rotation_head.eval()

        if state_dict is None:
            ckpt = str(AG_POSE_CKPT.fetch()) if ckpt_path is None else ckpt_path
            state_dict = torch.load(ckpt, map_location="cpu", weights_only=True)

        # Load pose_mlp2, rotation_estimator, translation_estimator, size_estimator
        # All keys start with "estimator.<submodule>.*" — strip "estimator." prefix.
        # _HEAD_PREFIXES is defined at module level.
        rotation_state = {
            k[len("estimator.") :]: v
            for k, v in state_dict.items()
            if any(k.startswith(p) for p in _HEAD_PREFIXES)
        }
        rotation_head.load_state_dict(rotation_state, strict=True)

        return cls(rotation_head)

    def forward(
        self,
        pre_pose_feat: torch.Tensor,  # (B, 384, 96)
        c: torch.Tensor,  # (B, 3)
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """
        Run rotation head forward pass.

        Parameters
        ----------
        pre_pose_feat
            Pre-pose feature of shape (B, 384, 96) from AGPoseBackbone.
        c
            Point cloud centroid of shape (B, 3) for translation reconstruction.

        Returns
        -------
        pred_rotation : torch.Tensor
            Predicted rotation matrix of shape (B, 3, 3).
        pred_translation : torch.Tensor
            Predicted translation vector of shape (B, 3).
        pred_size : torch.Tensor
            Predicted object size of shape (B, 3).
        """
        r, t, s = self.model(pre_pose_feat, c)
        return r.float(), t.float(), s.float()

    def component_precision(self) -> Precision:
        return Precision.float

    def get_input_spec(self, batch_size: int = 1) -> InputSpec:
        return {
            "pre_pose_feat": TensorSpec(
                shape=(batch_size, 384, 96),
                dtype="float32",
                io_type=IoType.TENSOR,
                description="Pre-pose feature (B,384,96) from AGPoseBackbone",
            ),
            "c": TensorSpec(
                shape=(batch_size, 3),
                dtype="float32",
                io_type=IoType.TENSOR,
                description="Point cloud centroid for translation reconstruction",
            ),
        }

    def get_output_spec(self, batch_size: int = 1) -> OutputSpec:
        return {
            "pred_rotation": TensorSpec(
                shape=(batch_size, 3, 3),
                dtype="float32",
                io_type=IoType.TENSOR,
                description="Predicted 3x3 rotation matrix",
            ),
            "pred_translation": TensorSpec(
                shape=(batch_size, 3),
                dtype="float32",
                io_type=IoType.TENSOR,
                description="Predicted translation vector (metres)",
            ),
            "pred_size": TensorSpec(
                shape=(batch_size, 3),
                dtype="float32",
                io_type=IoType.TENSOR,
                description="Predicted object size (metres)",
            ),
        }


class AGPoseCollection(WorkbenchModelCollection):
    """
    AGPose as a WorkbenchModelCollection.
    Component A (backbone)      : AGPoseBackbone  — float
    Component B (rotation_head) : AGPoseRotationHead — float
    """

    def __init__(
        self,
        backbone: AGPoseBackbone,
        rotation_head: AGPoseRotationHead,
    ) -> None:
        super().__init__({"backbone": backbone, "rotation_head": rotation_head})
        self.backbone = backbone
        self.rotation_head = rotation_head

    @classmethod
    def from_pretrained(cls, ckpt_path: str | None = None) -> AGPoseCollection:
        # Load state_dict once — shared with both sub-components to avoid
        # downloading and torch.load-ing epoch_30.pt twice.
        ckpt = str(AG_POSE_CKPT.fetch()) if ckpt_path is None else ckpt_path
        state_dict = torch.load(ckpt, map_location="cpu", weights_only=True)
        backbone = AGPoseBackbone.from_pretrained(state_dict=state_dict)
        rotation_head = AGPoseRotationHead.from_pretrained(state_dict=state_dict)
        return cls(backbone, rotation_head)

    @classmethod
    def get_eval_dataset_classes(cls) -> list[type]:
        return [NocsReal275Dataset]

    def get_evaluator(self) -> AGPoseEvaluator:
        data_dir = str(NOCS_REAL275_ASSET.fetch(extract=True))
        return AGPoseEvaluator(data_dir=data_dir)
