IMAGE_EMBEDDINGS, HIGH_RES_1, HIGH_RES_2, SPARSE_EMBEDDING, PIX_FEAT = range(5)


class SAM2InputImageLayout(Enum):
    RGB = 0
    BGR = 1


class SAM2App(CollectionAppEvaluateProtocol):
    """
    This class consists of light-weight "app code" that is required to perform end to end inference with Segment-Anything-2 Model.

    The app uses 2 models:
      * encoder (Given input image, emits image embeddings, high-resolution features to be used by decoder)
      * decoder (image embeddings and high-resolution features --> predicted segmentation masks and scores)
    """

    # In eval, feed the decoder pix_feat (embeddings + no_mem_embed), as
    # predict_embeddings does for SAM2.1 configs with directly_add_no_mem_embed.
    use_pix_feat = True

    def __init__(
        self,
        encoder_input_img_size: int,
        mask_threshold: float,
        input_image_channel_layout: SAM2InputImageLayout,
        sam2_encoder: Callable[
            [torch.Tensor, torch.Tensor, torch.Tensor],
            tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor],
        ],
        sam2_decoder: Callable[
            [torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor],
            tuple[torch.Tensor, torch.Tensor],
        ],
    ) -> None:
        """
        Initializes the segmentation model with encoder and decoder components.

        Parameters
        ----------
        encoder_input_img_size
          Size of input image for the encoder.
        mask_threshold
          Threshold value used to binarize the predicted masks.
        input_image_channel_layout
          Channel layout ("RGB" or "BGR") expected by the encoder.
        sam2_encoder
          SAM2 encoder. Must match input & output of each model part generated by qai_hub_models.models.sam2.model.SAM2Encoder
          Takes image to produce the image embeddings and high-resolutions features for sam2 decoder
        sam2_decoder
          SAM2 decoder. Must match input and output of qai_hub_models.models.sam2.model.SAM2Decoder.
          Takes image embeddings and high-resolution features to produce segmentation masks and confidence scores.
        """
        self.sam2_encoder = sam2_encoder
        self.sam2_decoder = sam2_decoder
        self.mask_threshold = mask_threshold
        self.encoder_input_img_size = encoder_input_img_size
        self.box = None
        self.normalize_coords = True
        self.mask_input = None
        self.input_image_channel_layout = input_image_channel_layout

    def predict(self, *args: Any, **kwargs: Any) -> tuple[torch.Tensor, torch.Tensor]:
        return self.predict_mask_from_points(*args, **kwargs)

    def predict_mask_from_points(
        self,
        pixel_values_or_image: torch.Tensor | np.ndarray | Image | list[Image],
        point_coords: torch.Tensor,
        point_labels: torch.Tensor,
        return_logits: bool = False,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """
        Predicts segmentation masks from input image(s) and point-based prompts.

        This function combines the embedding generation and mask prediction steps.
        It first encodes the input image(s) to obtain image embeddings and high-resolution
        features, then uses the provided point coordinates and labels to predict segmentation masks.

        Parameters
        ----------
        pixel_values_or_image
          PIL image
          or
          numpy array (B H W C x uint8) or (H W C x uint8)
            channel layout consistent with self.input_image_channel_layout
          or
          pyTorch tensor (B C H W x int8, value range is [0, 255])
            channel layout consistent with self.input_image_channel_layout
          Where B-Batch_size, N-Num_Points, H-Height, W-Width, C-Channel
        point_coords
          Coordinates of points used as prompts (shape: [N, 2] or [B, N, 2]).
        point_labels
          Labels for the points (shape: [N] or [B, N]).
        return_logits
          If True, return raw logits; otherwise, apply thresholding. Defaults to False.

        Returns
        -------
        upscaled_masks : torch.Tensor
          Shape [b, 1, <input image spatial dims>].
          The predicted segmentation masks, upscaled to original size.
          Where b = number of input images.
        scores : torch.Tensor
          Shape [b, 1].
          Confidence scores for each predicted mask.
          Where b = number of input images.
        """
        (
            image_embeddings,
            high_res_features1,
            high_res_features2,
            sparse_embedding,
            input_images_original_size,
        ) = self.predict_embeddings(
            pixel_values_or_image,
            point_coords,
            point_labels,
        )
        return self.predict_mask_from_points_and_embeddings(
            image_embeddings,
            high_res_features1,
            high_res_features2,
            sparse_embedding,
            input_images_original_size,
            return_logits,
        )

    def predict_embeddings(
        self,
        pixel_values_or_image: torch.Tensor | np.ndarray | Image | list[Image],
        point_coords: torch.Tensor,
        point_labels: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, tuple[int, int]]:
        """
        Generates image embeddings and high-resolution features from input image(s).

        This function processes the input image(s) through a transformation pipeline and
        a series of encoder splits to produce image embeddings and high-resolution features
        required for downstream tasks such as segmentation.

        Parameters
        ----------
        pixel_values_or_image
          PIL image
          or
          numpy array (B H W C x uint8) or (H W C x uint8)
            channel layout consistent with self.input_image_channel_layout
          or
          pyTorch tensor (B C H W x int8, value range is [0, 255])
            channel layout consistent with self.input_image_channel_layout
          Where B-Batch_size, N-Num_Points, H-Height, W-Width, C-Channel
        point_coords
          Coordinates of points used as prompts (shape: [N, 2] or [B, N, 2]).
        point_labels
          Labels for the points (shape: [N] or [B, N]).

        Returns
        -------
        image_embeddings : torch.Tensor
          Shape [1,256,64,64]. The image embeddings from the encoder.
        high_res_features1 : torch.Tensor
          Shape [1, 32, 256, 256]. First set of high-resolution features.
        high_res_features2 : torch.Tensor
          Shape [1, 64, 128, 128]. Second set of high-resolution features.
        sparse_embeddings : torch.Tensor
          Shape [1, N+1, 256]. The sparse embeddings from the prompt encoder.
        input_images_original_size : tuple[int, int]
          Original size of input image (BEFORE reshape to fit encoder input size).

        Notes
        -----
        It is faster to run this once on an image (compared to the entire encoder / decoder pipeline)
        if masks will be predicted several times on the same image.
        """
        # Translate input to torch tensor of shape [N, C, H, W]
        if isinstance(pixel_values_or_image, Image):
            pixel_values_or_image = [pixel_values_or_image]
        if isinstance(pixel_values_or_image, list):
            NCHW_int8_torch_frames = torch.cat(
                [
                    preprocess_PIL_image(
                        x.convert(self.input_image_channel_layout.name), True
                    )
                    for x in pixel_values_or_image
                ]
            )
        elif isinstance(pixel_values_or_image, np.ndarray):
            NCHW_int8_torch_frames = numpy_image_to_torch(pixel_values_or_image, True)
        else:
            NCHW_int8_torch_frames = pixel_values_or_image

        # Resize input image to the encoder's desired input size.
        input_images_original_size = (
            NCHW_int8_torch_frames.shape[2],
            NCHW_int8_torch_frames.shape[3],
        )
        # Run encoder
        image = resize(
            NCHW_int8_torch_frames,
            [self.encoder_input_img_size, self.encoder_input_img_size],
        )

        # Expand point_coords and point_labels to include a batch dimension, if necessary
        if len(point_coords.shape) == 2:
            point_coords = torch.unsqueeze(point_coords, 0)
        if len(point_labels.shape) == 1:
            point_labels = torch.unsqueeze(point_labels, 0)

        h, w = input_images_original_size
        point_coords = point_coords.clone().float()
        point_coords[..., 0] = point_coords[..., 0] / w
        point_coords[..., 1] = point_coords[..., 1] / h

        (
            image_embeddings,
            high_res_features1,
            high_res_features2,
            sparse_embedding,
            pix_feat,
        ) = self.sam2_encoder(image, point_coords, point_labels.float())

        # Use pix_feat (image_embeddings + no_mem_embed) when the model uses it,
        # so downstream code and tests see the same embeddings as
        # SAM2ImagePredictor.set_image.
        sam2 = getattr(self.sam2_encoder, "sam2", None)
        if sam2 is not None and getattr(sam2, "directly_add_no_mem_embed", False):
            image_embeddings = pix_feat.detach()

        return (
            image_embeddings,
            high_res_features1,
            high_res_features2,
            sparse_embedding,
            input_images_original_size,
        )

    def predict_mask_from_points_and_embeddings(
        self,
        image_embeddings: torch.Tensor,
        high_res_features1: torch.Tensor,
        high_res_features2: torch.Tensor,
        sparse_embedding: torch.Tensor,
        input_images_original_size: tuple[int, int],
        return_logits: bool = False,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """
        Predicts segmentation masks from image embeddings and point-based prompts.

        This function takes image embeddings, high-resolution features, and user-provided
        point coordinates and labels to generate segmentation masks using a decoder.
        The resulting masks are upscaled to the original image size and optionally thresholded.

        Parameters
        ----------
        image_embeddings
          The image embeddings from the encoder [1,256,64,64].
        high_res_features1
          First set of high-resolution features [1, 32, 256, 256].
        high_res_features2
          Second set of high-resolution features [1, 64, 128, 128].
        sparse_embedding
          The sparse embeddings from the prompt encoder [1, N+1, 256].
        input_images_original_size
          Original size of input image (BEFORE reshape to fit encoder input size).
        return_logits
          If True, return raw logits; otherwise, apply thresholding.

        Returns
        -------
        upscaled_masks : torch.Tensor
          Shape [b, 1, <input image spatial dims>].
          The predicted segmentation masks, upscaled to original size.
        scores : torch.Tensor
          Shape [b, 1].
          Confidence scores for each predicted mask.
        """
        # Run decoder
        masks, scores = self.sam2_decoder(
            image_embeddings,
            high_res_features1,
            high_res_features2,
            sparse_embedding,
        )

        # Upscale masks
        upscaled_masks = mask_postprocessing(masks, input_images_original_size)

        # Apply mask threshold
        if not return_logits:
            upscaled_masks = upscaled_masks > self.mask_threshold

        return upscaled_masks, scores

    @classmethod
    def from_components(
        cls,
        models: Sequence[ExecutableModelProtocol] | Sequence[AsyncOnDeviceModel],
    ) -> Self:
        """Build from collection components ordered [encoder, decoder]."""
        return cls(
            ENCODER_IMG_SIZE,
            MASK_THRESHOLD,
            SAM2InputImageLayout.RGB,
            models[0],  # type: ignore[arg-type]
            models[1],  # type: ignore[arg-type]
        )

    def run_model_for_eval(
        self,
        model_input: Generator[AsyncOnDeviceResult] | tuple[torch.Tensor, ...],
        model_batch_size: int,
    ) -> CollectionModelEvalGenerator:
        point_coords: ChunkedTensor
        point_labels: ChunkedTensor
        # On device, each input arrives as a chunk tuple from successive next() calls.
        if isinstance(model_input, tuple):
            image, point_coords, point_labels = model_input
        else:
            image, point_coords, point_labels = cast(
                tuple[torch.Tensor, ...], tuple(next(model_input) for _ in range(3))
            )
        encoder_spec = cast(Any, self.sam2_encoder).get_input_spec()
        point_coords, point_labels = pad_prompt_points(
            point_coords, point_labels, encoder_spec["unnorm_coords"][0][1]
        )
        # Eval inputs are in the model input frame, so normalize by the encoder size.
        norm_coords = map_chunks(point_coords, lambda c: c / ENCODER_IMG_SIZE)

        # The encoder may be an on-device model taking per-job chunk tuples.
        encoder_out = cast(Any, self.sam2_encoder)(image, norm_coords, point_labels)
        embeddings_index = PIX_FEAT if self.use_pix_feat else IMAGE_EMBEDDINGS
        decoder_inputs: tuple[Any, ...]
        if isinstance(encoder_out, AsyncOnDeviceResult):
            yield encoder_out
            features = cast(tuple[torch.Tensor, ...], encoder_out.wait())
            decoder_inputs = tuple(
                features[i].split(1, dim=0)
                for i in (embeddings_index, HIGH_RES_1, HIGH_RES_2, SPARSE_EMBEDDING)
            )
        else:
            yield tuple(encoder_out)
            decoder_inputs = tuple(
                encoder_out[i]
                for i in (embeddings_index, HIGH_RES_1, HIGH_RES_2, SPARSE_EMBEDDING)
            )

        output = self.sam2_decoder(*decoder_inputs)
        result = output if isinstance(output, AsyncOnDeviceResult) else tuple(output)
        yield result
        return result

    @classmethod
    def get_calibration_data(
        cls,
        collection_model: WorkbenchModelCollection,
        component_name: str,
        input_specs: dict[str, InputSpec] | None = None,
        num_samples: int | None = None,
    ) -> DatasetEntries:
        model = collection_model.components[component_name]
        input_spec = (
            input_specs[component_name] if input_specs else model.get_input_spec()
        )
        batch_size = get_batch_size(input_spec) or 1

        encoder: BaseModel | None = None
        if "decoder" in model._get_name().lower():
            # Use the component explicitly named "encoder" when present.
            # Fall back to the first component whose name contains "encoder".
            components = collection_model.components
            encoder_name = next(
                (name for name in ("encoder", "image_encoder") if name in components),
                next(
                    (name for name in components if "encoder" in name.lower()),
                    None,
                ),
            )
            if not encoder_name:
                raise ValueError(
                    "Could not find encoder component in collection model."
                )
            _enc = components[encoder_name]
            assert isinstance(_enc, BaseModel)
            encoder = _enc

        calibration_dataset_cls = collection_model.get_calibration_dataset_cls()
        assert calibration_dataset_cls is not None
        dataset = instantiate_dataset(
            calibration_dataset_cls,
            DatasetSplit.TRAIN,
            input_spec=encoder.get_input_spec() if encoder else input_spec,
        )
        num_samples = num_samples or dataset.default_num_calibration_samples()
        num_samples = (num_samples // batch_size) * batch_size
        print(f"Loading {num_samples} calibration samples.")
        torch_dataset = sample_dataset(dataset, num_samples)
        dataloader = DataLoader(torch_dataset, batch_size=batch_size)
        inputs: list[list[torch.Tensor | np.ndarray]] = [
            [] for _ in range(len(input_spec))
        ]
        for sample_input, _ in dataloader:
            if encoder is not None:
                n = len(encoder.get_input_spec())
                sample_input = encoder(
                    *(
                        sample_input[:n]
                        if isinstance(sample_input, (list, tuple))
                        else [sample_input]
                    )
                )
                if isinstance(sample_input, (tuple, list)):
                    sample_input = sample_input[: len(input_spec)]
            elif isinstance(sample_input, (list, tuple)):
                sample_input = sample_input[: len(input_spec)]
                if len(input_spec) == 1:
                    sample_input = sample_input[0]
            if isinstance(sample_input, (tuple, list)):
                for i, tensor in enumerate(sample_input):
                    inputs[i].append(tensor)
            else:
                inputs[0].append(sample_input)
        return make_hub_dataset_entries(tuple(inputs), list(input_spec.keys()))
